export function getHistoryReviewAnswer(fileName: string) {
  return REVIEW_ANSWERS[fileName];
}

function isArchitectureHistory(question: Question) {
  return question.fileName.includes("建筑史") || question.subject.includes("建築史");
}

function getEssayTemplate(question: Question): EssayTemplateId {
  if (question.year === 2014 && question.question_number === "13") return "urban-remodelling";
  if (question.year === 2016 && question.question_number === "9") return "tectonic-comparison";
  if (question.year === 2019 && question.question_number === "5") return "cultural-fusion";
  if ([2020, 2022].includes(question.year) && ["4", "5"].includes(question.question_number)) return "heritage";
  if (question.question_number === "3" && question.year >= 2024) return "building-four-axis";
  return "style-background";
}

export function getHistoryPracticeQuestions(questions: Question[]): HistoryPracticeQuestion[] {
  return questions
    .filter(isArchitectureHistory)
    .flatMap<HistoryPracticeQuestion>((question) => {
      if (question.category === "専門1") {
        return [{ ...question, mode: "word-bank" as const, formLabel: "語群マッチング" }];
      }
      if (question.category === "専門2-2") {
        return [{ ...question, mode: "essay" as const, template: getEssayTemplate(question), formLabel: "論述・作図" }];
      }
      return [] as HistoryPracticeQuestion[];
    })
    .sort((a, b) => b.year - a.year || a.question_number.localeCompare(b.question_number));
}

export function getEssayTemplateById(id?: EssayTemplateId) {
  return ESSAY_TEMPLATES.find((template) => template.id === id) ?? ESSAY_TEMPLATES[1];
}
